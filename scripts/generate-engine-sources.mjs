// Single generator for every downloadable kit engine (kits 1–9) and the shared sample helper.
// Each pure .mjs module is imported directly by the browser demo and embedded as a string
// in the downloaded starter, so both run the same code.
// Usage: node scripts/generate-engine-sources.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const dataDir = resolve(dirname(fileURLToPath(import.meta.url)), '../artifacts/starter-kits/src/data');

export const engineSources = [
  { input: 'sample-helpers.mjs', output: 'sample-helpers-source.ts', exportName: 'sampleHelpersSource' },
  { input: 'learning-engines.mjs', output: 'learning-engine-source.ts', exportName: 'learningEngineSource' },
  { input: 'interest-maximiser-engine.mjs', output: 'kit-engine-sources.ts', exportName: 'interestMaximiserEngineSource' },
  { input: 'spend-explorer-engine.mjs', output: 'kit-engine-sources.ts', exportName: 'spendExplorerEngineSource' },
  { input: 'card-guard-engine.mjs', output: 'kit-engine-sources.ts', exportName: 'cardGuardEngineSource' },
  { input: 'payment-pinger-engine.mjs', output: 'kit-engine-sources.ts', exportName: 'paymentPingerEngineSource' },
  { input: 'card-to-sheet-sync-engine.mjs', output: 'kit-engine-sources.ts', exportName: 'cardToSheetSyncEngineSource' },
  { input: 'swipe-n-save-engine.mjs', output: 'kit-engine-sources.ts', exportName: 'swipeNSaveEngineSource' },
];

export async function renderEngineSources() {
  const outputs = new Map();
  for (const { input, output, exportName } of engineSources) {
    const source = await readFile(resolve(dataDir, input), 'utf8');
    const path = resolve(dataDir, output);
    const body = outputs.get(path) ?? '// Generated by scripts/generate-engine-sources.mjs. Do not edit by hand.\n';
    outputs.set(path, `${body}export const ${exportName} = ${JSON.stringify(source)};\n`);
  }
  return outputs;
}

export async function staleEngineSources() {
  const stale = [];
  for (const [path, expected] of await renderEngineSources()) {
    const current = await readFile(path, 'utf8').catch(() => undefined);
    if (current !== expected) stale.push(path);
  }
  return stale;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = await staleEngineSources();
    for (const path of stale) console.error(`Generated engine source is missing or stale: ${path}. Run node scripts/generate-engine-sources.mjs.`);
    if (stale.length) process.exitCode = 1;
  } else {
    for (const [path, content] of await renderEngineSources()) await writeFile(path, content);
  }
}
