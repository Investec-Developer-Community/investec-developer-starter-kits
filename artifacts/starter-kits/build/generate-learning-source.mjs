// Generate a portable string for browser downloads and Node-based catalog tooling.
// No eval: the browser imports the .mjs functions; downloads contain the same source.
import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../src/data/learning-engines.mjs', import.meta.url), 'utf8');
const output = '// Generated by build/generate-learning-source.mjs. Do not edit by hand.\n'
  + `export const learningEngineSource = ${JSON.stringify(source)};\n`;
const destination = new URL('../src/data/learning-engine-source.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('Learning engine download source is stale. Run node build/generate-learning-source.mjs.');
} else {
  await writeFile(destination, output);
}
