// Stale-generated-file check: every generated *-source.ts must embed its .mjs engine exactly.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { engineSources, renderEngineSources, staleEngineSources } from '../../../../scripts/generate-engine-sources.mjs';

test('generated engine sources are current (run node scripts/generate-engine-sources.mjs if this fails)', async () => {
  assert.deepEqual(await staleEngineSources(), []);
  for (const [path, expected] of await renderEngineSources()) {
    assert.equal(await readFile(path, 'utf8'), expected, `${path} is stale`);
  }
});

test('each generated export equals its .mjs input byte-for-byte', async () => {
  const outputs = new Map();
  for (const { input, output, exportName } of engineSources) {
    if (!outputs.has(output)) outputs.set(output, await import(new URL(`../data/${output}`, import.meta.url).href));
    const embedded = outputs.get(output)[exportName];
    const source = await readFile(new URL(`../data/${input}`, import.meta.url), 'utf8');
    assert.equal(embedded, source, `${output}#${exportName} must match ${input}`);
  }
});

test('one generator owns every engine source, including kits 1–9 and the sample helper', () => {
  const inputs = engineSources.map(entry => entry.input);
  for (const input of [
    'sample-helpers.mjs', 'learning-engines.mjs', 'interest-maximiser-engine.mjs', 'spend-explorer-engine.mjs',
    'card-guard-engine.mjs', 'payment-pinger-engine.mjs', 'card-to-sheet-sync-engine.mjs', 'swipe-n-save-engine.mjs',
  ]) {
    assert.ok(inputs.includes(input), `${input} must be generated by scripts/generate-engine-sources.mjs`);
  }
  assert.equal(new Set(inputs).size, inputs.length);
});
